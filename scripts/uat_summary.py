"""
Summarise the user acceptance test responses.

Reads docs/evaluation/uat_responses.csv (one row per participant, one
column per statement, ratings 1-5) and prints the mean for each statement,
each section and overall. The README's evaluation table is this script's
output with --markdown.

Usage (from the repository root):
    python scripts/uat_summary.py
    python scripts/uat_summary.py --markdown
"""
import argparse
import csv
from pathlib import Path
from statistics import mean

CSV_PATH = Path(__file__).resolve().parent.parent / "docs" / "evaluation" / "uat_responses.csv"

STATEMENTS = {
    "ui1":   "The app has a clean and visually appealing design that is easy on the eyes.",
    "ui2":   "The colour scheme and visual style of the app feel professional and consistent throughout.",
    "ui3":   "The navigation icons and buttons are clearly labelled and easy to identify.",
    "func1": "The lesson content generated by the app was relevant and helpful for understanding the topic.",
    "func2": "The quiz questions accurately tested my understanding of the topic I studied.",
    "func3": "The AI chatbot (Chukky) provided useful and relevant responses to my questions.",
    "ux1":   "I was able to navigate through the app easily without needing external guidance.",
    "ux2":   "The overall learning flow, from lesson to quiz to feedback, felt smooth and logical.",
    "ux3":   "I would feel comfortable using this app regularly as part of my studies.",
}

SECTIONS = {
    "User interface": ["ui1", "ui2", "ui3"],
    "Functionality":  ["func1", "func2", "func3"],
    "User experience": ["ux1", "ux2", "ux3"],
}


def load(path: Path) -> list[dict]:
    with open(path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    for row in rows:
        for key in STATEMENTS:
            value = int(row[key])
            if not 1 <= value <= 5:
                raise ValueError(f"{row['participant']} {key}: rating {value} is outside 1-5")
            row[key] = value
    return rows


def summarise(rows: list[dict]) -> dict:
    statement_means = {k: mean(r[k] for r in rows) for k in STATEMENTS}
    section_means = {
        name: mean(r[k] for r in rows for k in keys) for name, keys in SECTIONS.items()
    }
    overall = mean(r[k] for r in rows for k in STATEMENTS)
    return {"n": len(rows), "statements": statement_means,
            "sections": section_means, "overall": overall}


def print_plain(s: dict) -> None:
    print(f"Participants: {s['n']}\n")
    for name, keys in SECTIONS.items():
        print(f"{name}: {s['sections'][name]:.2f}")
        for k in keys:
            print(f"  {k:<6} {s['statements'][k]:.2f}  {STATEMENTS[k]}")
    print(f"\nOverall: {s['overall']:.2f}")


def print_markdown(s: dict) -> None:
    print(f"Ratings from {s['n']} participants, 1 = strongly disagree, 5 = strongly agree.\n")
    print("| Section | Statement | Mean |")
    print("|---|---|---|")
    for name, keys in SECTIONS.items():
        for k in keys:
            print(f"| {name} | {k}: {STATEMENTS[k]} | {s['statements'][k]:.2f} |")
        print(f"| **{name}** | **Section mean** | **{s['sections'][name]:.2f}** |")
    print(f"| **All** | **Overall mean (all nine statements)** | **{s['overall']:.2f}** |")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("--markdown", action="store_true", help="print a Markdown table")
    parser.add_argument("--csv", type=Path, default=CSV_PATH, help="path to the responses CSV")
    args = parser.parse_args()
    summary = summarise(load(args.csv))
    print_markdown(summary) if args.markdown else print_plain(summary)
